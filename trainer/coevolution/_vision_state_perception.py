"""Per-step vision-grounded ``<state>`` markup via the 35B multimodal judge.

T2.17 (2026-05-05): the actor's per-step prompt previously consumed a
deterministic Python-rendered ``<state>...</state>`` block (see
:mod:`trainer.coevolution._state_to_markup`).  Cold-start SFT data, by
contrast, was generated by GPT-5 looking at the *actual frame* using
the canonical :func:`vlm_wrapper.schema.build_system_prompt` /
:func:`build_user_message` prompts (see
``cold_start/generate_cold_start_actor_gymv.py`` lines ~725–755) — so
the SFT distribution carries visually-grounded entities (``player
ship``, ``enemy orb``, ``enemy shot``, ``cave wall``) while the live
training markup at the same step shows generic priors (``HUD bar``,
``score``, ``cave path``).  This distribution drift is one of the main
reasons the 9B actor under-performs Gemini / Qwen-VL teachers on the
same games.

This module closes the gap by calling the 35B judge (running with
``MULTIMODAL=1`` on port 8001) at every actor decision step with a
prompt that:

1. Embeds the canonical schema rules (gymv grid coordinates, ontology
   vocabulary, section ordering) lifted from
   :data:`vlm_wrapper.schema.SCHEMA_SPEC`.
2. Anchors the model on the SFT label distribution via real cold-start
   examples loaded from
   :func:`vlm_wrapper.few_shot_library.get_few_shot_examples` (when
   available) — these are the exact ``<state>...</state>`` blocks GPT-5
   produced during cold-start, so 35B has a concrete demo of the
   expected vocabulary / coordinate scheme.
3. Caps entities at 12 and uses placeholder labels in the schematic
   exemplar (so the model fills slots with frame content rather than
   regurgitating example labels — a verbatim-copy failure mode we
   observed when the only exemplar was a real TF3 trajectory).

We do NOT re-use the full ``build_system_prompt`` payload because the
35B (Qwen3.5-35B-A3B) follows the ~5 kB GPT-5 prompt unreliably — it
defaults to pixel-coordinates and produces duplicated entities.  The
trimmed prompt below keeps gymv grid coordinates and the SFT ontology
intact while staying small enough for 35B to follow consistently.

* **Same format contract** — ``<state>...<entities>...<attributes>...``
  block, parsable by the existing :func:`parse_schema_output` helper
  (and downstream :mod:`trainer.coevolution._state_to_markup`
  consumers, which tolerate partial markup defensively).
* **Same call shape** — synchronous ``str`` return value (the async
  variant just wraps a thread-pool / semaphore-bounded call).
* **Graceful degradation** — on any failure (judge offline, timeout,
  malformed output, missing frame) we silently return the deterministic
  ``state_to_markup`` output, so the training loop is never blocked by
  vision unavailability.

Hot-path safety
---------------
* **Concurrency cap** via :class:`asyncio.Semaphore` (default 12,
  matches the 35B's ``max_num_seqs=16`` minus headroom for the
  game-schema and harness-validator paths).
* **LRU cache** keyed on a SHA-1 hash of the data URL; identical frames
  (e.g. paused or repeated states) skip the LLM call entirely.
* **Hard timeout** (default 6 s) enforced via :func:`asyncio.wait_for` so
  a stuck judge can never wedge the rollout.
* **Optional frequency throttle** — call every N steps and reuse the
  prior markup in between (set
  ``vision_state_perception_every_n_steps > 1`` in config).

Output validation
-----------------
We perform a *minimal* well-formedness check (presence of opening
``<state>`` tag) before returning the LLM output.  We do NOT enforce
full schema validation here — downstream parsers handle malformed
markup defensively, and forcing strict validation would push edge cases
to the deterministic fallback unnecessarily.
"""

